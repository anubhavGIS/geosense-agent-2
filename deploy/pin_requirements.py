"""
pin_requirements.py - Phase 5, Exercise 2: pin the container requirements to the versions
of the geosense environment.

Reads deploy/requirements-backend.in and deploy/requirements-frontend.in (the hand-trimmed
package lists) and writes requirements-backend.txt and requirements-frontend.txt beside
them, with every package pinned to the version installed in the environment this script
runs in: the versions the tools were tested with on the laptop become the versions inside
the images. Local build tags are dropped (torch 2.11.0+cu128 -> 2.11.0, because the
Dockerfile installs the CPU build of the same version). A package of the list that is not
installed here is written unpinned and reported.

Run from the project root in the geosense environment:
    python deploy\\pin_requirements.py
"""
import re
import sys
from datetime import date
from importlib.metadata import distributions
from pathlib import Path

DEPLOY = Path(__file__).resolve().parent
LISTS = ['requirements-backend', 'requirements-frontend']
LINE = re.compile(r'^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?P<extras>\[[^\]]*\])?'
                  r'(?P<rest>.*)$')


def canonical(name):
    """PEP 503 normalisation: 'Scikit_Learn' and 'scikit-learn' are the same project."""
    return re.sub(r'[-_.]+', '-', name).lower()


def installed_versions():
    """{canonical name: version} of every distribution in this environment."""
    versions = {}
    for dist in distributions():
        name = dist.metadata['Name']
        if name:
            versions[canonical(name)] = dist.version
    return versions


def pin(line, versions):
    """One line of a .in file -> the pinned line and a note ('' when all is well)."""
    stripped = line.strip()
    if not stripped or stripped.startswith('#'):
        return line.rstrip('\n'), ''
    m = LINE.match(stripped)
    name, extras, rest = m.group('name'), m.group('extras') or '', m.group('rest')
    comment = rest[rest.index('#'):].rstrip() if '#' in rest else ''
    version = versions.get(canonical(name))
    if version is None:
        return f'{name}{extras}{("  " + comment) if comment else ""}', \
               f'{name}: not installed here - left unpinned'
    public = version.split('+')[0]                   # 2.11.0+cu128 -> 2.11.0
    note = f'{name}: {version} -> {public}' if public != version else ''
    pinned = f'{name}{extras}=={public}'
    return (f'{pinned}  {comment}' if comment else pinned), note


def main():
    versions = installed_versions()
    python = '.'.join(str(v) for v in sys.version_info[:3])
    for stem in LISTS:
        src, dst = DEPLOY / f'{stem}.in', DEPLOY / f'{stem}.txt'
        out = [f'# {dst.name} - generated by deploy/pin_requirements.py on {date.today()} '
               f'from {src.name}',
               f'# with the versions of the geosense environment (Python {python}). '
               f'Edit the .in file, not this one.']
        notes, n_pinned = [], 0
        for line in src.read_text(encoding='utf-8').splitlines():
            pinned, note = pin(line, versions)
            out.append(pinned)
            if note:
                notes.append(note)
            if '==' in pinned and not pinned.lstrip().startswith('#'):
                n_pinned += 1
        dst.write_text('\n'.join(out) + '\n', encoding='utf-8')
        print(f'{dst.name}: {n_pinned} packages pinned')
        for note in notes:
            print(f'  note: {note}')


if __name__ == '__main__':
    main()
